require('dotenv').config();
const express=require('express'),cors=require('cors'),helmet=require('helmet'),cron=require('node-cron');
const {processMonthlyBilling}=require('./services/automatedBillingService');
const {processDailyReminders}=require('./services/billingReminderService');
const app=express();
app.use(helmet({crossOriginResourcePolicy:false}));
const allowedOrigins=String(process.env.CORS_ORIGINS||'http://localhost:5173,http://127.0.0.1:5173').split(',').map(x=>x.trim()).filter(Boolean);
app.use(cors({origin:(origin,callback)=>{if(!origin||process.env.NODE_ENV!=='production'||allowedOrigins.includes(origin))return callback(null,true);return callback(new Error('Origin tidak diizinkan.'));},credentials:true}));
app.use(express.json({limit:'2mb'}));
app.use(express.urlencoded({extended:true}));
app.get('/api/health',(req,res)=>res.json({success:true,mode:String(process.env.DEMO_MODE).toLowerCase()==='true'?'demo':'database',service:'Billing Life Media API'}));
app.use('/api',require('./middleware/auditMutation'));
app.use('/api/auth',require('./routes/authRoutes'));
app.use('/api/files',require('./routes/fileRoutes'));
app.use('/api/mobile/customer',require('./routes/mobileCustomerRoutes'));
app.use('/api/mobile/technician',require('./routes/mobileTechnicianRoutes'));
app.use('/api/notifications',require('./routes/notificationRoutes'));
app.use('/api/activity',require('./routes/activityRoutes'));
app.use('/api/customers',require('./routes/customerRoutes'));
app.use('/api/billings',require('./routes/billingRoutes'));
app.use('/api/payments',require('./routes/paymentRoutes'));
app.use('/api/pppoe',require('./routes/pppoeRoutes'));
app.use('/api/complaints',require('./routes/complaintRoutes'));
app.use('/api/technicians',require('./routes/technicianRoutes'));
app.use('/api/reports',require('./routes/reportRoutes'));
app.use('/api/analytics',require('./routes/analyticsRoutes'));
app.use('/api/admins',require('./routes/adminRoutes'));
app.use((req,res)=>res.status(404).json({success:false,message:'Endpoint tidak ditemukan.'}));
app.use(require('./middleware/errorHandler'));
cron.schedule('5 0 1 * *',async()=>{try{console.log('[CRON] Membuat tagihan bulanan...');console.log(await processMonthlyBilling())}catch(e){console.error('[CRON]',e.message)}},{timezone:'Asia/Jakarta'});
cron.schedule('0 9 * * *',async()=>{try{console.log('[CRON] Mengirim pengingat tagihan...');console.log(await processDailyReminders())}catch(e){console.error('[CRON REMINDER]',e.message)}},{timezone:'Asia/Jakarta'});
const port=Number(process.env.PORT||5000);app.listen(port,()=>console.log(`Billing Life Media API aktif di http://localhost:${port} | DEMO_MODE=${process.env.DEMO_MODE||'true'}`));
